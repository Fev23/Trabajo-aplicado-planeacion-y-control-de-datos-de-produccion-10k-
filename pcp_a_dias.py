def simular_taller(datos, col_pj):
    # Filtrar solo las remisiones que tienen carga para esta máquina
    datos_maq = datos[datos[col_pj] > 0].copy()
    datos_maq = datos_maq.sort_values(by='FECHA')

    # Calcular Índice WSPT (pj / Cant tipos)
    datos_maq['WSPT_INDEX'] = datos_maq[col_pj] / datos_maq['Cant tipos']

    reloj = datos_maq['FECHA'].min().replace(hour=0, minute=0, second=0)
    lista_pendientes = pd.DataFrame()
    procesados = []
    dias_unicos = sorted(datos['FECHA'].unique())

    reporte_diario = {}

    for dia in dias_unicos:
        dia_actual = pd.to_datetime(dia)
        if dia_actual.weekday() == 6: continue

        nuevos = datos_maq[datos_maq['FECHA'] == dia_actual].copy()
        pool = pd.concat([lista_pendientes, nuevos])

        # APLICACIÓN WSPT: Menor índice primero
        secuencia = pool.sort_values(by='WSPT_INDEX').reset_index(drop=True)

        terminados_hoy = []
        indices_ok = []
        limite_dia = dia_actual + pd.Timedelta(hours=24)

        if reloj < dia_actual: reloj = dia_actual

        for i, fila in secuencia.iterrows():
            if reloj + pd.Timedelta(hours=fila[col_pj]) > limite_dia: break

            reloj += pd.Timedelta(hours=fila[col_pj])
            if reloj.weekday() == 6: reloj += pd.Timedelta(days=1)

            info = fila.copy()
            info['FIN_REAL'] = reloj
            info['FLUJO'] = (reloj - fila['FECHA']).total_seconds() / 3600
            info['RETRASADO'] = reloj > fila['FECHA_PROMESA']
            procesados.append(info)
            terminados_hoy.append(info)
            indices_ok.append(i)

        lista_pendientes = secuencia.drop(indices_ok)
        reporte_diario[dia_actual.strftime('%Y-%m-%d')] = {
            'completados': len(terminados_hoy),
            'pendientes': len(lista_pendientes),
            'flujo_prom': pd.DataFrame(terminados_hoy)['FLUJO'].mean() if terminados_hoy else 0
        }

    return pd.DataFrame(procesados), reporte_diario

