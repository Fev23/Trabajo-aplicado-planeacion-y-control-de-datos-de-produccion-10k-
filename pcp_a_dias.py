# --- REGLA: PROMESA (3er día a las 15:00, saltando domingos) ---
def calcular_promesa(fecha_llegada):
    promesa = fecha_llegada + pd.Timedelta(days=2)
    if promesa.weekday() == 6: # Si es domingo, pasar al lunes
        promesa += pd.Timedelta(days=1)
    return promesa.replace(hour=15, minute=0, second=0)

df['FECHA_PROMESA'] = df['FECHA'].apply(calcular_promesa)

