    # Si es domingo, el taller no abre.
    if dia_actual.weekday() == 6:
        continue

    # Cargar pedidos del día y unir con pendientes de ayer
    nuevos = df[df['FECHA'] == dia_actual].copy()
    pool = pd.concat([lista_pendientes, nuevos])

    # REGLA SPT: Ordenar por p_j de menor a mayor
    secuencia = pool.sort_values(by='p_j').reset_index(drop=True)

    terminados_hoy = []
    indices_procesados = []
    limite_dia = dia_actual + pd.Timedelta(hours=24)

    # Sincronizar reloj al inicio del día si estaba atrasado
    if reloj_global < dia_actual:
        reloj_global = dia_actual

    for i, fila in secuencia.iterrows():
        # ¿El trabajo cabe en las 24h de hoy?
        if reloj_global + pd.Timedelta(hours=fila['p_j']) > limite_dia:
            break

        reloj_global += pd.Timedelta(hours=fila['p_j'])

        # Saltar domingo en producción si el reloj cae ahí
