# --- NUEVA FUNCIÓN: CÁLCULO DE TIEMPO DE FLUJO PROMEDIO ---
def calcular_tiempo_flujo_global():
    # Consolidamos el fin de cada remisión (máximo entre figurado y mallas)
    f_res = res_fig[['Nº REMISION', 'FECHA', 'FIN_REAL']]
    m_res = res_mall[['Nº REMISION', 'FECHA', 'FIN_REAL']]

    total = pd.merge(f_res, m_res, on=['Nº REMISION', 'FECHA'], how='outer', suffixes=('_f', '_m'))

    # El tiempo de salida real es el último proceso terminado
    total['SALIDA_FINAL'] = total[['FIN_REAL_f', 'FIN_REAL_m']].max(axis=1)

    # Tiempo de Flujo = Salida - Llegada (convertido a días)
    total['TIEMPO_FLUJO'] = (total['SALIDA_FINAL'] - total['FECHA']).dt.total_seconds() / (24 * 3600)

    return round(total['TIEMPO_FLUJO'].mean(), 2)

