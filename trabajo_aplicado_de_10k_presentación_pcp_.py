def calcular_tiempo_flujo():
    f_res = res_fig[['Nº REMISION', 'FECHA', 'FIN_REAL']]
    m_res = res_mall[['Nº REMISION', 'FECHA', 'FIN_REAL']]
    total = pd.merge(f_res, m_res, on=['Nº REMISION', 'FECHA'], how='outer', suffixes=('_f', '_m'))
    total['SALIDA_FINAL'] = total[['FIN_REAL_f', 'FIN_REAL_m']].max(axis=1)

    tiempos = []
    for _, row in total.iterrows():
        llegada, salida = row['FECHA'], row['SALIDA_FINAL']
        doms = sum(1 for d in pd.date_range(llegada.date(), salida.date(), freq='D') if d.weekday() == 6)
        horas_habiles = ((salida - llegada).total_seconds() / 3600) - (doms * 24)
        tiempos.append(max(0, horas_habiles))
    return round(sum(tiempos) / len(tiempos), 2)

def calcular_indicadores():
    f_res, m_res = res_fig[['Nº REMISION', 'FECHA_PROMESA', 'FIN_REAL']], res_mall[['Nº REMISION', 'FECHA_PROMESA', 'FIN_REAL']]
