# ----------------------------
# 3) Algoritmo Common Due Date
#    - Si d <= Cmax: sets A y B (B FIFO, A LIFO)
#    - Si d > Cmax: LPT y retrasar inicio hasta que el último termine en d
# ----------------------------
def secuencia_cdd_min_abs(jobs):
    """
    jobs: lista de dicts con {"remision":id, "p":horas}
    devuelve: (secuencia_ids, start_offset_h)
    """
    # ordenar SPT
    jobs_sorted = sorted(jobs, key=lambda x: (x["p"], x["remision"]))
    n = len(jobs_sorted)
    if n == 0:
        return [], 0.0

    d = 15.0  # horas desde 00:00
    Cmax = sum(j["p"] for j in jobs_sorted)

    # Caso d > Cmax: todo sería "early", conviene LPT y retrasar inicio
    if d > Cmax + 1e-12:
        seq = [j["remision"] for j in sorted(jobs_sorted, key=lambda x: (-x["p"], x["remision"]))]
        start_offset = d - Cmax  # retraso para terminar cerca de 15:00
        return seq, start_offset


    R = Cmax - d
    L = d
    A = []
    B = []

    # i = n..1 (empezar por el más grande dentro de SPT)
    for j in reversed(jobs_sorted):
        if R >= L:
            A.append(j)
            R -= j["p"]
        else:
            B.append(j)
            L -= j["p"]

    seq_B = [j["remision"] for j in B]
    seq_A = [j["remision"] for j in reversed(A)]
    seq = seq_B + seq_A
    return seq, 0.0

def simular_dia_centro(df_sub, dia_operativo, centro_nombre):
    """
    Simula un día y un centro, usando secuencia CDD.
    Retorna dataframe con start/C/E/T/U por remisión.
    """
    # due date del día
    d_dt = due_date_3pm(dia_operativo)


    if centro_nombre == "MP":
        out = df_sub.copy()
        out["maquina"] = "MP"
        out["start"] = d_dt
        out["C_j"] = d_dt
        out["E_j_h"] = 0.0
        out["T_j_h"] = 0.0
        out["U_j"] = 0
        out["d_comun"] = d_dt
        out["pos"] = 1
        return out[[REM_COL, "maquina", "dia_operativo", "pos", "p_horas", "start", "C_j", "d_comun", "E_j_h", "T_j_h", "U_j"]]

    # armar lista jobs
    jobs = [{"remision": int(r[REM_COL]), "p": float(r["p_horas"])} for _, r in df_sub.iterrows()]

    seq_ids, offset_h = secuencia_cdd_min_abs(jobs)

    # inicio del día (00:00) con posible offset si d > Cmax
    start_day = datetime.combine(pd.to_datetime(dia_operativo).date(), time(0,0))
    start_day = move_to_monday_0000(start_day)
    reloj = start_day + timedelta(hours=float(offset_h))

    # mapa rápido p
    p_map = {j["remision"]: j["p"] for j in jobs}

    rows = []
    for k, rid in enumerate(seq_ids, start=1):
        pj = p_map[rid]
        st = reloj
        en = add_work_hours_skip_sundays(st, pj)

        E = max((d_dt - en).total_seconds()/3600.0, 0.0)
        T = max((en - d_dt).total_seconds()/3600.0, 0.0)
        U = 1 if T > 1e-12 else 0

        rows.append({
            REM_COL: rid,
            "maquina": centro_nombre,
            "dia_operativo": pd.to_datetime(dia_operativo), # Removed .date() to ensure Timestamp consistency
            "pos": k,
            "p_horas": pj,
            "start": st,
            "C_j": en,
            "d_comun": d_dt,
            "E_j_h": E,
            "T_j_h": T,
            "U_j": U
        })
        reloj = en

    return pd.DataFrame(rows)

