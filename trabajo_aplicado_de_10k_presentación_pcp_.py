# 3. MOTOR DE CÁLCULO WSPT
def procesar_maquina(datos, col_pj):
    df_m = datos[datos[col_pj] > 0].copy()
    df_m['WSPT'] = df_m[col_pj] / df_m['Cant tipos']
    reloj = df_m['FECHA'].min().replace(hour=0, minute=0)
    backlog, finalizados, resumen_diario = pd.DataFrame(), [], []
    hoy = df_m['FECHA'].min()
    ultima_fecha_datos = df_m['FECHA'].max()

    while hoy <= ultima_fecha_datos or not backlog.empty:
        if hoy.weekday() == 6:
            hoy += pd.Timedelta(days=1)
            continue

        pool = pd.concat([backlog, df_m[df_m['FECHA'] == hoy]])
        if not pool.empty:
            pool = pool.sort_values(by=['WSPT', 'Cant tipos'], ascending=[True, False], kind='stable')
            horas_hoy, hechos_hoy, ids_terminados = 0, 0, []
            if reloj < hoy: reloj = hoy

            for idx, row in pool.iterrows():
                pj = row[col_pj]
                if horas_hoy > 0 and (horas_hoy + pj > 24): break

                inicio_tarea = reloj
                reloj += pd.Timedelta(hours=pj)
                horas_hoy += pj
                if reloj.weekday() == 6: reloj += pd.Timedelta(days=1)

                row_copy = row.copy()
                row_copy['INICIO_REAL'] = inicio_tarea
                row_copy['FIN_REAL'] = reloj
                row_copy['SEMANA'] = inicio_tarea.isocalendar()[1]
                finalizados.append(row_copy)
                ids_terminados.append(idx)
                hechos_hoy += 1
                if horas_hoy >= 24: break

            backlog = pool.drop(ids_terminados)
            resumen_diario.append({'Fecha': hoy.date(), 'Hechos': hechos_hoy, 'Pendientes': len(backlog), 'Semana': hoy.isocalendar()[1]})

        hoy += pd.Timedelta(days=1)
        if hoy > ultima_fecha_datos + pd.Timedelta(days=100): break

    return pd.DataFrame(finalizados), pd.DataFrame(resumen_diario)

