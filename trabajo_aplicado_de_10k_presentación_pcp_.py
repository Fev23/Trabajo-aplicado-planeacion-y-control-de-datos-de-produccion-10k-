import pandas as pd
import numpy as np
import io
import requests
import plotly.express as px
from datetime import datetime, timedelta

# 1. CARGA Y PREPARACIÓN DE DATOS (GitHub)
url = "https://github.com/Fev23/Datos-entrada-Taller-Plan-Eduyn/raw/refs/heads/main/Apartado%202.xlsx"
try:
    response = requests.get(url)
    df = pd.read_excel(io.BytesIO(response.content))
except:
    print("Error al cargar datos. Verifique la conexión.")
    exit()

df.columns = [c.strip() for c in df.columns]

# Parámetros del modelo
V1, V2 = 1.0, 1.5
ALPHA, H, W = 40000, 130000, 200000

df['FECHA_DT'] = pd.to_datetime(df['FECHA'])
T_INICIO = df['FECHA_DT'].min().replace(hour=0, minute=0)

def calcular_promesa(f):
    p = f + pd.Timedelta(days=2)
    if p.weekday() == 6: p += pd.Timedelta(days=1)
    return p.replace(hour=15, minute=0, second=0)

df['PROMESA_H'] = (df['FECHA_DT'].apply(calcular_promesa) - T_INICIO).dt.total_seconds() / 3600
df = df.sort_values(by=['Cant tipos', 'p_j'], ascending=[False, True]).reset_index(drop=True)

# 2. MOTOR DE SIMULACIÓN
def simular(factor_v):
    reloj, c_ent, c_ant, c_tar = 0, 0, 0, 0
    batch, data_rastreo = [], []
    contador = 1

    for idx, row in df.iterrows():
        pj_real = row['p_j'] / factor_v
        inicio_job = reloj
        reloj += pj_real
        batch.append({
            'id': str(row['Nº REMISION']),
            'inicio': inicio_job,
            'fin': reloj,
            'due': row['PROMESA_H']
        })

        # Lógica de grupos: cada 6 horas o al final
        if reloj % 6.0 < pj_real or idx == len(df) - 1:
            d_k = reloj
            for job in batch:
                tardanza = max(0, d_k - job['due'])
                c_ent += (d_k * ALPHA) / len(batch)
                c_ant += (d_k - job['fin']) * H
                c_tar += tardanza * W

                # Cálculo de tiempos reales para el Gantt (basado en T_INICIO)
                t_real_inicio = T_INICIO + timedelta(hours=job['inicio'])
                t_real_fin = T_INICIO + timedelta(hours=job['fin'])
                t_real_despacho = T_INICIO + timedelta(hours=d_k)

                data_rastreo.append({
                    'Secuencia': contador,
                    'Remision': job['id'],
                    'Inicio_DT': t_real_inicio,
                    'Fin_DT': t_real_fin,
                    'Despacho_DT': t_real_despacho,
                    'Fin_Prod': round(job['fin'], 2),
                    'Salida_Batch': round(d_k, 2),
                    'Retraso_H': round(tardanza, 2),
                    'Costo_T': round(tardanza * W, 0)
                })
                contador += 1
            batch = []
    return [c_ent, c_ant, c_tar], pd.DataFrame(data_rastreo)

# Ejecución de escenarios
costos_v1, rastreo_v1 = simular(V1)
costos_v2, rastreo_v2 = simular(V2)

