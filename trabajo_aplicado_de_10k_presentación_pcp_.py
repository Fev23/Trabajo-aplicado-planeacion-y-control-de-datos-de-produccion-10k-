def procesar_semana_dinamica(df_semana, col_pj, regla, batch_size=5):
    df_m = df_semana[df_semana[col_pj] > 0].copy()
    if df_m.empty: return []

    reloj = df_m['FECHA'].min() - pd.Timedelta(days=df_m['FECHA'].min().weekday())
    reloj = reloj.replace(hour=0, minute=0, second=0)

    finalizados = []
    unscheduled = df_m.copy()

    while not unscheduled.empty:
        if reloj.weekday() == 6:
            reloj += pd.Timedelta(days=1)
            reloj = reloj.replace(hour=0, minute=0, second=0)

        disp = unscheduled[unscheduled['FECHA'] <= reloj].copy()
        if disp.empty:
            reloj = unscheduled['FECHA'].min()
            continue

        dj_minus_t = (disp['FECHA_PROMESA'] - reloj).dt.total_seconds() / 3600.0
        pj = disp[col_pj]
        wj = disp['W_j']

        if regla == 'CR':
            disp['PRIORIDAD'] = dj_minus_t / pj
            asc = True
        elif regla == 'MST':
            disp['PRIORIDAD'] = dj_minus_t - pj
            asc = True
        elif regla == 'ATC':
            K, p_avg = 2.0, max(pj.mean(), 1e-5)
            slack = np.maximum(0, dj_minus_t - pj)
            disp['PRIORIDAD'] = (wj / pj) * np.exp(-slack / (K * p_avg))
            asc = False
        elif regla == 'COVERT':
            K, p_avg = 2.0, max(pj.mean(), 1e-5)
            slack = np.maximum(0, dj_minus_t - pj)
            cov_factor = np.maximum(0, 1 - (slack / (K * p_avg)))
            disp['PRIORIDAD'] = (wj / pj) * cov_factor
            asc = False
        elif regla == 'RSI':
            slack = dj_minus_t - pj
            time_to_due = np.maximum(1e-5, dj_minus_t)
            disp['PRIORIDAD'] = slack / time_to_due
            asc = True

        disp = disp.sort_values(by=['PRIORIDAD', 'W_j'], ascending=[asc, False], kind='stable')
        batch = disp.head(batch_size)

        for idx, row in batch.iterrows():
            if reloj.weekday() == 6:
                reloj += pd.Timedelta(days=1)
                reloj = reloj.replace(hour=0, minute=0, second=0)
            inicio_tarea = reloj
            reloj = agregar_horas_habiles(reloj, row[col_pj])
            row_copy = row.copy()
            row_copy['INICIO_REAL'] = inicio_tarea
            row_copy['FIN_REAL'] = reloj
            row_copy['C_j_horas'] = (reloj - row_copy['FECHA']).total_seconds() / 3600.0
            finalizados.append(row_copy)
            unscheduled = unscheduled.drop(idx)
    return finalizados

