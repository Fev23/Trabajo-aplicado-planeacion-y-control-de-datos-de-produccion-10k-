def is_sunday(dt: datetime) -> bool:
    return dt.weekday() == 6

def move_to_monday_0000(dt: datetime) -> datetime:
    if not is_sunday(dt):
        return dt
    return datetime.combine((dt + timedelta(days=1)).date(), time(0,0))

def add_work_hours_skip_sundays(start: datetime, hours: float) -> datetime:
    """Suma horas de trabajo (lunes-sábado 24h). Domingo no avanza."""
    if hours < 0:
        raise ValueError("hours debe ser >= 0")
    cur = move_to_monday_0000(start)
    remaining = float(hours)

    while remaining > 1e-12:
        cur = move_to_monday_0000(cur)

        cur_hour = cur.hour + cur.minute/60 + cur.second/3600 + cur.microsecond/3600e6
        avail = 24.0 - cur_hour
        if avail <= 1e-12:
            cur = datetime.combine((cur + timedelta(days=1)).date(), time(0,0))
            continue

        step = avail if remaining >= avail else remaining
        cur = cur + timedelta(hours=step)
        remaining -= step

        if cur.hour == 0 and cur.minute == 0 and cur.second == 0 and cur.microsecond == 0:
            cur = datetime.combine(cur.date(), time(0,0))

    return cur

