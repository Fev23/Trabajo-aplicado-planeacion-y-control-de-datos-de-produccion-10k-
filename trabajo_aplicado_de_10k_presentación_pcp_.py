def programar_wspt_disponibles(df_jobs: pd.DataFrame, maquina: str) -> pd.DataFrame:
    if df_jobs.empty:
        return pd.DataFrame(columns=["maquina","remision","r_j","p_horas","w_j","ratio_p_w","start","C_j","flow_time_h"])

    tmp = df_jobs.sort_values("r_j").copy()
    pendientes = set(tmp.index)
    t = move_to_monday_0000(min(tmp["r_j"]))

    rows = []
    while pendientes:
        disponibles = [i for i in pendientes if tmp.at[i,"r_j"] <= t]

        if not disponibles:
            i_next = min(pendientes, key=lambda i: tmp.at[i,"r_j"])
            t = move_to_monday_0000(tmp.at[i_next,"r_j"])
            continue

        def key(i):
            pj = float(tmp.at[i,"p_horas"])
            w  = int(tmp.at[i,"w_j"]) if int(tmp.at[i,"w_j"]) > 0 else 1
            return (pj / w, pj, tmp.at[i,"r_j"], int(tmp.at[i,REM_COL]))

        i = min(disponibles, key=key)

        rj = tmp.at[i,"r_j"]
        pj = float(tmp.at[i,"p_horas"])
        w  = int(tmp.at[i,"w_j"]) if int(tmp.at[i,"w_j"]) > 0 else 1

        start = move_to_monday_0000(max(t, rj))
        end   = add_work_hours_skip_sundays(start, pj)

        flow_h = (end - rj).total_seconds()/3600.0

        rows.append({
            "maquina": maquina,
            "remision": int(tmp.at[i,REM_COL]),
            "r_j": rj,
            "p_horas": pj,
            "w_j": w,
            "ratio_p_w": pj / w,
            "start": start,
            "C_j": end,
            "flow_time_h": flow_h
        })

        t = end
        pendientes.remove(i)

    return pd.DataFrame(rows)

