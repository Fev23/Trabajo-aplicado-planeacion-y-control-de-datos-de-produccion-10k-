def agregar_horas_habiles(fecha_inicio, horas):
    actual = fecha_inicio
    restante = horas
    while restante > 0:
        if actual.weekday() == 6: # Es domingo, saltar
            actual += pd.Timedelta(days=1)
            actual = actual.replace(hour=0, minute=0, second=0)

        dias_para_domingo = 6 - actual.weekday()
        proximo_domingo = (actual + pd.Timedelta(days=dias_para_domingo)).replace(hour=0, minute=0, second=0)
        horas_al_domingo = (proximo_domingo - actual).total_seconds() / 3600.0

        if restante <= horas_al_domingo:
            actual += pd.Timedelta(hours=restante)
            restante = 0
        else:
            actual = proximo_domingo + pd.Timedelta(days=1)
            restante -= horas_al_domingo
    return actual

def aplicar_regla_ordenamiento(df_m, col_pj, regla):
    if regla == 'FCFS': df_m = df_m.sort_values(by='FECHA')
    elif regla == 'SPT': df_m = df_m.sort_values(by=col_pj)
    elif regla == 'WSPT':
        df_m['PRIO'] = df_m[col_pj] / df_m['W_j']
        df_m = df_m.sort_values(by='PRIO')
    elif regla == 'LPT': df_m = df_m.sort_values(by=col_pj, ascending=False)
    elif regla == 'EDD': df_m = df_m.sort_values(by='d_j_horas')
    elif regla == 'MST':
        df_m['PRIO'] = df_m['d_j_horas'] - df_m[col_pj]
        df_m = df_m.sort_values(by='PRIO')
    elif regla == 'CR':
        df_m['PRIO'] = df_m['d_j_horas'] / df_m[col_pj]
        df_m = df_m.sort_values(by='PRIO')
    elif regla == 'WLPT':
        df_m['PRIO'] = df_m[col_pj] * df_m['W_j']
        df_m = df_m.sort_values(by='PRIO', ascending=False)
    return df_m

def procesar_semana_estatica(df_semana, col_pj, regla):
    df_m = df_semana[df_semana[col_pj] > 0].copy()
    if df_m.empty: return []

    inicio_semana = df_m['FECHA'].min() - pd.Timedelta(days=df_m['FECHA'].min().weekday())
    inicio_semana = inicio_semana.replace(hour=0, minute=0, second=0)
    df_m['d_j_horas'] = (df_m['FECHA_PROMESA'] - inicio_semana).dt.total_seconds() / 3600.0

    df_m = aplicar_regla_ordenamiento(df_m, col_pj, regla)

    finalizados = []
    reloj = inicio_semana

    for _, row in df_m.iterrows():
        if reloj < row['FECHA']: reloj = row['FECHA'].replace(hour=0, minute=0, second=0)
        if reloj.weekday() == 6:
            reloj += pd.Timedelta(days=1)
            reloj = reloj.replace(hour=0, minute=0, second=0)

        inicio_tarea = reloj
        reloj = agregar_horas_habiles(reloj, row[col_pj])

        row_copy = row.copy()
        row_copy['INICIO_REAL'] = inicio_tarea
        row_copy['FIN_REAL'] = reloj
        row_copy['C_j_horas'] = (reloj - row_copy['FECHA']).total_seconds() / 3600.0
        finalizados.append(row_copy)
    return finalizados

def procesar_dia_estatico(df_dia, col_pj, regla, reloj_global):
    df_m = df_dia[df_dia[col_pj] > 0].copy()
