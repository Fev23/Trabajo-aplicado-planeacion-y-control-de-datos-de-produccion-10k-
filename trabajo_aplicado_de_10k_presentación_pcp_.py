def partir_intervalo_por_dia(start: datetime, end: datetime):
    out = []
    cur = start
    while cur < end:
        if cur.weekday() == 6:
            cur = datetime.combine((cur + timedelta(days=1)).date(), time(0,0))
            continue
        next_midnight = datetime.combine((cur + timedelta(days=1)).date(), time(0,0))
        seg_end = min(end, next_midnight)
        hrs = (seg_end - cur).total_seconds()/3600.0
        if hrs > 0:
            out.append((cur.date(), hrs))
        cur = seg_end
    return out

