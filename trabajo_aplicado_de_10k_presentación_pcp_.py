    total['PROMESA'] = total['FECHA_PROMESA_f'].fillna(total['FECHA_PROMESA_m'])

    # Nivel de servicio (OTD)
    nivel_servicio = ( (total['SALIDA_MAX'] <= total['PROMESA']).mean() * 100 ).round(2)
    total['RETRASO'] = (total['SALIDA_MAX'] - total['PROMESA']).dt.total_seconds() / 3600
